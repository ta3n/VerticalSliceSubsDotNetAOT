using Aspire.Hosting.Kubernetes;

namespace AppHost;

/// <summary>
/// Kubernetes compute environment (Aspire.Hosting.Kubernetes, preview). Opt-in with <c>Kubernetes:Enabled=true</c>:
/// <c>aspire run</c> is unaffected, but with an environment in the model <c>aspire publish</c> writes a Helm chart for
/// the AppHost's resources and <c>aspire deploy</c> installs it into the current kubectl context (Helm 4.2 or later on
/// the PATH). It sits beside the hand-written chart in <c>deploy/helm</c>, which stays the one Argo CD syncs.
/// </summary>
internal static class KubernetesPublishing
{
  public static IResourceBuilder<KubernetesEnvironmentResource> AddKubernetes(
    this IDistributedApplicationBuilder builder
  )
  {
    var @namespace = builder.Configuration.Required<string>("Kubernetes:Namespace");

    return builder.AddKubernetesEnvironment("k8s")
      .WithHelm(
        helm => helm.WithChartName("subscription-management-aspire")
          .WithChartDescription("Subscription Management generated by the Aspire AppHost.")
          .WithReleaseName("subscription-management")
          .WithNamespace(@namespace)
      );
  }
}